'use client';

import { motion } from 'framer-motion';
import { ExternalLink, Database, Cpu, FileText } from 'lucide-react';

interface DatasetCard {
    icon: React.ReactNode;
    title: string;
    source: string;
    github: string;
    description: string;
    usedFor: string;
    license: string;
    extra?: string;
}

function Card({ card, delay }: { card: DatasetCard; delay: number }) {
    return (
        <motion.div
            initial={{ opacity: 0, y: 16 }}
            animate={{ opacity: 1, y: 0 }}
            transition={{ delay }}
            className="cyber-card p-5 border border-cyber-primary/20 hover:border-cyber-primary/40 transition-colors"
        >
            <div className="flex items-start gap-3 mb-3">
                <div className="text-cyber-primary mt-0.5">{card.icon}</div>
                <div>
                    <h3 className="font-display text-base text-cyber-primary font-bold">{card.title}</h3>
                    <p className="text-xs text-cyber-muted font-mono">{card.source}</p>
                </div>
            </div>
            <p className="text-sm text-gray-300 leading-relaxed mb-3">{card.description}</p>
            <div className="text-xs space-y-1.5">
                <div>
                    <span className="text-cyber-muted">Used for: </span>
                    <span className="text-gray-300">{card.usedFor}</span>
                </div>
                <div>
                    <span className="text-cyber-muted">License: </span>
                    <span className="text-cyber-success">{card.license}</span>
                </div>
                {card.extra && (
                    <div>
                        <span className="text-cyber-muted">Note: </span>
                        <span className="text-gray-400">{card.extra}</span>
                    </div>
                )}
            </div>
            <a
                href={card.github}
                target="_blank"
                rel="noopener noreferrer"
                className="mt-3 flex items-center gap-1.5 text-xs text-cyber-primary hover:text-cyber-primary/80 transition-colors font-mono"
            >
                <ExternalLink className="h-3 w-3" />
                {card.github}
            </a>
        </motion.div>
    );
}

