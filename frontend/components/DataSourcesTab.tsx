'use client';

import { ExternalLink, Database, Cpu, FileText, Info } from 'lucide-react';

interface DatasetCard {
    icon: React.ReactNode;
    title: string;
    source: string;
    github: string;
    description: string;
    usedFor: string;
    license: string;
    extra?: string;
}

function Card({ card }: { card: DatasetCard }) {
    const host = card.github.replace('https://', '').replace(/\/$/, '');
    return (
        <article className="cyber-card flex flex-col p-5">
            <div className="flex items-start gap-3">
                <span className="flex h-9 w-9 flex-shrink-0 items-center justify-center rounded-lg bg-cyber-primary/10 text-cyber-primary ring-1 ring-cyber-primary/20">
                    {card.icon}
                </span>
                <div className="min-w-0">
                    <h3 className="text-[15px] font-semibold text-cyber-text">{card.title}</h3>
                    <p className="truncate font-mono text-xs text-cyber-muted">{card.source}</p>
                </div>
                <span className="pill ml-auto flex-shrink-0">{card.license}</span>
            </div>
            <p className="mt-4 text-sm leading-relaxed text-cyber-muted">{card.description}</p>
            <dl className="mt-4 space-y-3 border-t border-cyber-border pt-4 text-xs">
                <div>
                    <dt className="eyebrow mb-1">Used for</dt>
                    <dd className="leading-relaxed text-cyber-text/90">{card.usedFor}</dd>
                </div>
                {card.extra && (
                    <div>
                        <dt className="eyebrow mb-1">Note</dt>
                        <dd className="leading-relaxed text-cyber-text/90">{card.extra}</dd>
                    </div>
                )}
            </dl>
            <a
                href={card.github}
                target="_blank"
                rel="noopener noreferrer"
                className="mt-auto inline-flex items-center gap-1.5 pt-5 text-xs font-medium text-cyber-primary hover:underline"
            >
                {host}
                <ExternalLink className="h-3 w-3" />
            </a>
        </article>
    );
}

